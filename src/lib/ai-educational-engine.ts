/**
 * محاولة الاتصال بـ Google Gemini إذا توفر مفتاح GEMINI_API_KEY
 */
export async function callGeminiIfConfigured(
  apiKey: string,
  params: AiRequestParams
): Promise<AiEnhancedContent | null> {
  if (!apiKey || !apiKey.trim()) return null;

  try {
    const { reportType, title, subject, gradeLevel, requestedCounts = {} } = params;
    const objCount = Math.max(requestedCounts.objectives || 3, 3);
    const stepCount = Math.max(requestedCounts.steps || 4, 4);
    const outcomeCount = Math.max(requestedCounts.outcomes || 3, 3);

    const prompt = `أنت خبير تربوي ومعلم سعودي خبير في وزارة التعليم بالمملكة العربية السعودية وإعداد شواهد تقويم الأداء المدرسي A4.
المطلوب صياغة محتوى تقرير توثيقي بالكامل باللغة العربية بأسلوب تعليمي رسمي رصين ومهني ومباشر وفق التفاصيل التالية:
- عنوان التقرير الفعلي: "${title}"
- نوع التقرير: "${reportType}"
- المادة (إن وجدت): "${subject || 'عام'}"
- الصف (إن وجد): "${gradeLevel || 'عام'}"

يجب أن ترتبط جميع الأهداف والخطوات والنتائج ارتباطاً وثيقاً ومباشراً بالعنوان الفعلي وتذكر موضوعه وأنشطته بدقة.

المطلوب إرجاع كائن JSON فقط (بدون أي علامات تشفير أو نص خارجي) بالهيكل التالي تماماً:
{
  "objectives": [قائمة تحتوي بالضبط على ${objCount} أهداف تعليمية سلوكية مباشرة متصلة بالعنوان],
  "steps": [قائمة تحتوي بالضبط على ${stepCount} خطوات وإجراءات تنفيذ عملية ومتسلسلة لموضوع العنوان],
  "outcomes": [قائمة تحتوي بالضبط على ${outcomeCount} نتائج ومؤشرات أثر واقعية قابلة للقياس],
  "notes": "ملاحظات وتوصيات ختامية للاستدامة والتطوير لا تتجاوز سطرين"
}`;

    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 6000); // 6s timeout

    const res = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey.trim()}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: {
            temperature: 0.4,
            responseMimeType: 'application/json',
          },
        }),
        signal: controller.signal,
      }
    );

    clearTimeout(timeoutId);

    if (!res.ok) return null;

    const data = await res.json();
    const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!rawText) return null;

    const parsed = JSON.parse(rawText);
    if (
      Array.isArray(parsed.objectives) &&
      Array.isArray(parsed.steps) &&
      Array.isArray(parsed.outcomes)
    ) {
      return {
        objectives: parsed.objectives.map((s: any) => String(s).trim()).filter(Boolean),
        steps: parsed.steps.map((s: any) => String(s).trim()).filter(Boolean),
        outcomes: parsed.outcomes.map((s: any) => String(s).trim()).filter(Boolean),
        notes: String(parsed.notes || '').trim(),
      };
    }
  } catch (err) {
    console.warn('Gemini API call skipped or timed out, falling back to semantic engine:', err);
  }

  return null;
}
