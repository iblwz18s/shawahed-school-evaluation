/**
 * تنظيف واستخراج جوهر الموضوع الفعلي من عنوان التقرير
 */
export function extractCoreTopic(rawTitle: string): string {
  if (!rawTitle || !rawTitle.trim()) return '';

  let t = rawTitle.trim();
  // إزالة الكلمات الزائدة في بداية العنوان
  t = t.replace(
    /^(برنامج|نشاط|فعالية|مشروع|مبادرة|ورشة عمل|ورشة|دورة تدريبية|دورة|استراتيجية|خطة|تحليل نتائج|تحليل|زيارة صفية|زيارة تبادلية|زيارة|اجتماع|لقاء|الاحتفاء بـ|الاحتفاء بالـ|احتفاء بـ|تفعيل|أسبوع|معرض)\s*(تدريبية|مدرسية|تعليمية|تطبيقية)?\s*[:\-–—]?\s*/i,
    ''
  ).trim();

  // إزالة علامات التنصيص والرموز
  t = t.replace(/^["'«“]/, '').replace(/["'»”]$/, '').trim();

  return t || rawTitle.trim();
}

